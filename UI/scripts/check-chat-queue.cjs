const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../src/lib/chat-request-queue.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const exportsObject = {};
vm.runInNewContext(compiled.outputText, { exports: exportsObject });
const { ChatRequestQueue } = exportsObject;
const tick = () => new Promise(resolve => setImmediate(resolve));

(async () => {
  const calls = [];
  const completions = new Map();
  const queue = new ChatRequestQueue((sid, job) => {
    calls.push([sid, job]);
    return new Promise(resolve => completions.set(sid, resolve));
  }, () => {});
  queue.enqueue('first', 'initial');
  queue.enqueue('first', 'next');
  queue.enqueue('first', 'last');
  queue.enqueue('second', 'independent');
  assert.deepEqual(calls, [['first', 'initial'], ['second', 'independent']]);
  assert.equal(queue.items('first').length, 2);
  completions.get('first')(true);
  await tick();
  assert.deepEqual(calls.at(-1), ['first', 'next']);
  assert.equal(queue.isBusy('second'), true);
  completions.get('first')(false);
  await tick();
  assert.equal(queue.isBusy('first'), false);
  assert.equal(queue.items('first')[0], 'last');
  assert.equal(calls.length, 3, 'failure must pause the remaining queue');
  queue.enqueue('first', 'added while paused');
  assert.equal(calls.length, 3, 'adding a new request must not resume a paused queue');
  queue.remove('first', 1);
  queue.start('first');
  assert.deepEqual(calls.at(-1), ['first', 'last']);
  queue.enqueue('first', 'cancelled');
  queue.clear('first');
  completions.get('first')(true);
  completions.get('second')(true);
  await tick();
  assert.equal(calls.length, 4, 'cleared requests must never execute');
  queue.enqueue('third', 'running');
  queue.enqueue('third', 'remove');
  queue.remove('third', 0);
  completions.get('third')(true);
  await tick();
  assert.equal(calls.length, 5);
  assert.equal(queue.isBusy('third'), false);
  console.log('Chat queue checks passed: FIFO, session isolation, pause on error, cancellation and removal.');
})().catch(error => { console.error(error); process.exitCode = 1; });
